#!/usr/bin/env node
/**
 * Build a zero-dependency single-file ESM bundle (dist/gitlab.mjs) for the GitLab CI template,
 * print its sha256 digest, and optionally update the pinned runner_sha256 in templates/megalens-review.yml.
 *
 * Uses only Node 20 built-ins (no external bundler required).
 * Usage:
 *   node scripts/build-gitlab.mjs [--update-template]
 */
import { createHash } from 'node:crypto'
import { readFileSync, writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const root = join(dirname(fileURLToPath(import.meta.url)), '..')
const updateTemplate = process.argv.includes('--update-template')

// Topological dependency order of the pure-ESM modules used by the GitLab CI runner.
const MODULE_ORDER = [
  'src/redact.js',
  'src/diff.js',
  'src/findings.js',
  'src/format.js',
  'src/megalens-api.js',
  'src/engine.js',
  'src/gitlab-diff.js',
  'src/gitlab-format.js',
  'src/gitlab-api.js',
  'src/gitlab-runner.js',
  'src/gitlab-index.js',
]

// Collect node: built-in imports per module specifier so each built-in symbol is imported once at the top.
/** @type {Map<string, Set<string>>} */
const nodeImports = new Map()
const bodyChunks = []

for (const relPath of MODULE_ORDER) {
  const fullPath = join(root, relPath)
  let code = readFileSync(fullPath, 'utf8')

  // Extract `import { ... } from 'node:...'`
  code = code.replace(
    /^import\s*\{([^}]+)\}\s*from\s*['"](node:[^'"]+)['"]\s*;?\s*$/gm,
    (_m, names, mod) => {
      if (!nodeImports.has(mod)) nodeImports.set(mod, new Set())
      for (const n of names.split(',').map((s) => s.trim()).filter(Boolean)) {
        nodeImports.get(mod).add(n)
      }
      return ''
    },
  )

  // Strip local relative imports (`import ... from './...'`) — symbols are in shared top-level scope.
  code = code.replace(/^import\s+[\s\S]*?from\s*['"]\.\/[^'"]+['"]\s*;?\s*$/gm, '')

  // Strip re-export blocks (`export { ... }`) since symbols are already declared.
  code = code.replace(/^export\s*\{[\s\S]*?\}(?:\s*from\s*['"][^'"]+['"])?\s*;?\s*$/gm, '')

  // Convert `export const|let|var|function|async function|class` to local declarations.
  code = code.replace(/^export\s+(?=(?:async\s+)?(?:function|const|let|var|class)\b)/gm, '')

  bodyChunks.push(`// ─── ${relPath} ───\n${code.trim()}\n`)
}

const headerLines = [
  '#!/usr/bin/env node',
  '// Generated by scripts/build-gitlab.mjs — do not edit by hand.',
  '// Zero-dependency standalone MegaLens GitLab CI runner bundle (Node >= 20).',
  ...[...nodeImports.entries()]
    .sort(([a], [b]) => a.localeCompare(b))
    .map(([mod, syms]) => `import { ${[...syms].sort().join(', ')} } from '${mod}'`),
  '',
]

const entrypoint = `
// ─── Entrypoint ───
main().catch((err) => {
  const msg = err instanceof Error ? err.message : String(err)
  process.stderr.write(\`MegaLens error: \${errorText(msg)}\\n\`)
  process.exitCode = 1
})
`

const bundle = `${headerLines.join('\n')}\n${bodyChunks.join('\n')}\n${entrypoint}`
const outPath = join(root, 'dist', 'gitlab.mjs')
writeFileSync(outPath, bundle, 'utf8')

const sha256 = createHash('sha256').update(bundle, 'utf8').digest('hex')
console.log(`Built dist/gitlab.mjs (${Buffer.byteLength(bundle, 'utf8')} bytes)`)
console.log(`sha256: ${sha256}`)

if (updateTemplate) {
  const tplPath = join(root, 'templates', 'megalens-review.yml')
  const tpl = readFileSync(tplPath, 'utf8')
  const updated = tpl.replace(
    /(runner_sha256:\s*\n\s*default:\s*['"]?)[0-9a-f]{64}(['"]?)/,
    `$1${sha256}$2`,
  )
  if (updated === tpl && !tpl.includes(sha256)) {
    console.error('Could not update runner_sha256 in templates/megalens-review.yml')
    process.exit(1)
  }
  writeFileSync(tplPath, updated, 'utf8')
  console.log('Updated runner_sha256 in templates/megalens-review.yml')
}
